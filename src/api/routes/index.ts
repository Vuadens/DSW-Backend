import {Router} from 'express';
import {actividadRouter} from './actividad.routes';
import planRouter from './plan.routes';
import profesorRouter from './profesor.routes';
import {socioRouter} from "./socio.routes";
import claseRouter from './clase.routes';
import inscripcionRouter from './inscripcion.routes';
import {authRouter} from './auth.routes';
import {usuarioRouter} from './usuario.routes';
import {authenticate, authorize} from '../middlewares/auth.middleware';
import {Rol} from '@prisma/client';

export const apiRouter = Router();
apiRouter.get('/health', (_req, res) => res.json({status: 'ok'}));
apiRouter.use('/auth', authRouter);
apiRouter.use('/usuarios', authenticate, authorize(Rol.ADMINISTRADOR), usuarioRouter);
apiRouter.use('/planes', authenticate, planRouter);
apiRouter.use('/profesores', authenticate, profesorRouter);
apiRouter.use("/socios", authenticate, socioRouter);
apiRouter.use('/actividades', authenticate, actividadRouter);
apiRouter.use('/clases', authenticate, claseRouter);
apiRouter.use('/inscripciones', authenticate, inscripcionRouter);